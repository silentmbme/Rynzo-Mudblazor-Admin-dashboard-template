// Run from any directory: node scripts/sync-design.cjs [--check]
// No npm packages are needed. Edit Rynzo.Client/Theme/design-system.json, then regenerate.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'Rynzo.Client/Theme/design-system.json'), 'utf8'));
const { settings, palettes } = source;
const quote = value => JSON.stringify(value);
const banner = '// Generated by scripts/sync-design.cjs from Rynzo.Client/Theme/design-system.json. Do not edit.\n';

function color(variables, key, visited = new Set()) {
    if (visited.has(key)) throw new Error(`Circular token: ${key}`);
    visited.add(key);
    const value = variables[key];
    if (!value) throw new Error(`Missing token: ${key}`);
    const reference = /^var\((--[\w-]+)\)$/.exec(value);
    if (reference) return color(variables, reference[1], visited);
    if (/^#[\da-f]{6}$/i.test(value)) return value;
    const match = /^oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)$/.exec(value);
    if (!match) throw new Error(`Unsupported palette color: ${key} = ${value}`);
    const [, l, c, h] = match.map(Number);
    const a = c * Math.cos(h * Math.PI / 180), b = c * Math.sin(h * Math.PI / 180);
    const x = (l + .3963377774 * a + .2158037573 * b) ** 3;
    const y = (l - .1055613458 * a - .0638541728 * b) ** 3;
    const z = (l - .0894841775 * a - 1.291485548 * b) ** 3;
    return '#' + [4.0767416621 * x - 3.3077115913 * y + .2309699292 * z,
        -1.2684380046 * x + 2.6097574011 * y - .3413193965 * z,
        -.0041960863 * x - .7034186147 * y + 1.707614701 * z]
        .map(v => Math.round(Math.min(1, Math.max(0, v <= .0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - .055)) * 255).toString(16).padStart(2, '0')).join('');
}

const fields = {
    Primary: '--primary', PrimaryForeground: '--primary-foreground', Secondary: '--secondary',
    SecondaryForeground: '--secondary-foreground', Background: '--background', Foreground: '--foreground',
    Card: '--card', Muted: '--muted', MutedForeground: '--muted-foreground', Border: '--border', Input: '--input',
    Success: '--success', SuccessForeground: '--success-foreground', Destructive: '--destructive',
    DestructiveForeground: '--destructive-foreground', Warning: '--warning', WarningForeground: '--warning-foreground',
    Info: '--info', InfoForeground: '--info-foreground', Accent700: '--accent-700', Accent400: '--accent-400',
    Header: '--header', Sidebar: '--sidebar', SidebarForeground: '--sidebar-foreground'
};
let css = '/* Generated by scripts/sync-design.cjs from Rynzo.Client/Theme/design-system.json. Do not edit. */\n';
const cases = [];
for (const [skin, modes] of Object.entries(palettes)) {
    for (const mode of ['light', 'dark']) {
        const variables = modes[mode];
        if (!variables) throw new Error(`Missing ${skin}/${mode}`);
        css += `.rynzo-theme[data-skin="${skin}"][data-theme="${mode}"] {\n  color-scheme: ${mode};\n`;
        css += Object.entries(variables).map(([name, value]) => `  ${name}: ${value};`).join('\n') + '\n}\n';
        const colors = Object.values(fields).map(key => quote(color(variables, key)));
        const chartColors = Array.from({ length: 8 }, (_, i) => quote(color(variables, `--chart-${i + 1}`)));
        cases.push(`        (${quote(skin)}, ${mode === 'dark'}) => new(${colors.join(', ')}, [${chartColors.join(', ')}]),`);
    }
}
const paletteCs = banner + 'namespace Rynzo.Client.Theme;\n\n' +
    `public sealed record RynzoDesignPalette(${Object.keys(fields).map(name => `string ${name}`).join(', ')}, string[] ChartColors);\n\n` +
    'public static class RynzoDesignTokens\n{\n    public static RynzoDesignPalette Get(string skin, bool dark) => (skin, dark) switch\n    {\n' +
    cases.join('\n') + '\n        _ => Get("multicolor", dark)\n    };\n}\n';
const settingsCs = banner + 'namespace Rynzo.Client.Theme;\n\npublic static class RynzoThemeSettings\n{\n' +
    `    public static readonly string[] FontFamily = [${settings.fontFamily.map(quote).join(', ')}];\n` +
    `    public static readonly string[] HeadingFontFamily = [${(settings.headingFontFamily || settings.fontFamily).map(quote).join(', ')}];\n` +
    `    public static readonly string[] Skins = [${Object.keys(palettes).map(quote).join(', ')}];\n` +
    Object.entries(settings.fontSizes).map(([key, value]) => `    public const string ${key}FontSize = ${quote(value)};`).join('\n') + '\n' +
    ['controlRadius', 'drawerWidth', 'drawerMiniWidth', 'appbarHeight'].map(key => `    public const string ${key[0].toUpperCase() + key.slice(1)} = ${quote(settings[key])};`).join('\n') + '\n}\n';
const font = settings.fontFamily.map(name => name.includes(' ') ? `'${name}'` : name).join(', ');
const headingFont = (settings.headingFontFamily || settings.fontFamily).map(name => name.includes(' ') ? `'${name}'` : name).join(', ');
const foundationCss = '/* Generated by scripts/sync-design.cjs. Do not edit. */\n.rynzo-theme {\n' +
    `  --rynzo-font-family: ${font};\n  --rynzo-control-radius: ${settings.controlRadius};\n` +
    `  --rynzo-heading-font-family: ${headingFont};\n` +
    Object.entries(settings.fontSizes).map(([key, value]) => `  --rynzo-font-${key.toLowerCase()}: ${value};`).join('\n') + '\n' +
    Object.entries(settings.spacing).map(([key, value]) => `  --rynzo-space-${key}: ${value};`).join('\n') +
    '\n  --rynzo-shell-border: var(--border);\n}\n' +
    Object.entries(palettes).map(([skin, modes]) => `.rynzo-theme[data-skin="${skin}"] {\n` +
        `  --rynzo-dark-sidebar: ${color(modes.dark, '--sidebar')};\n` +
        `  --rynzo-dark-sidebar-foreground: ${color(modes.dark, '--sidebar-foreground')};\n` +
        `  --rynzo-dark-sidebar-border: ${color(modes.dark, '--border')};\n` +
        `  --rynzo-dark-sidebar-accent: ${color(modes.dark, '--primary')};\n}\n`).join('');
const outputs = {
    'Rynzo/wwwroot/theme/design-tokens.css': css,
    'Rynzo/wwwroot/theme/design-system.css': foundationCss,
    'Rynzo.Client/Theme/EdzenDesignTokens.g.cs': paletteCs,
    'Rynzo.Client/Theme/EdzenThemeSettings.g.cs': settingsCs
};
let stale = false;
for (const [file, contents] of Object.entries(outputs)) {
    const target = path.join(root, file);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) {
            console.error(`Out of date: ${file}`);
            stale = true;
        }
    } else fs.writeFileSync(target, contents);
}
if (stale) process.exitCode = 1;
else console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${Object.keys(outputs).length} design files; ${cases.length} palettes.`);
